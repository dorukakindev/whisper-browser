'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { EventEmitter } = require('node:events');
const { createAssistantOverlay } = require('../src/assistant-overlay');

test('native assistant accepts only its own frame; provider secrets and arbitrary actions are never forwarded', () => {
  const ipcMain = new EventEmitter(), window = new EventEmitter();
  const sent = [], views = [];
  const contents = () => Object.assign(new EventEmitter(), {
    mainFrame: {}, send: (channel, value) => sent.push({ channel, value }),
    isDestroyed: () => false, setWindowOpenHandler() {}, loadFile: async () => {}, close() {}, focus() {},
  });
  window.webContents = contents(); window.isDestroyed = () => false;
  window.getContentSize = () => [680, 780]; window.isFullScreen = () => false;
  window.contentView = { addChildView(view) { views.push(view); } };
  class View { constructor() { this.webContents = contents(); } setBackgroundColor() {} setBounds(value) { this.bounds = value; } setVisible(value) { this.visible = value; } }
  createAssistantOverlay({ window, WebContentsView: View, ipcMain });
  const view = views[0];
  const parent = { sender: window.webContents, senderFrame: window.webContents.mainFrame };
  const overlay = { sender: view.webContents, senderFrame: view.webContents.mainFrame };
  const foreign = { sender: contents(), senderFrame: {} };
  ipcMain.emit('assistant:action', foreign, { action: 'send', text: 'unauthorized' });
  ipcMain.emit('assistant:action', foreign, { action: 'settings' });
  ipcMain.emit('assistant:action', overlay, { action: 'openFile', text: 'secret' });
  ipcMain.emit('assistant:update', foreign, { messages: [{ text: 'spoofed' }] });
  ipcMain.emit('assistant:update', {sender:window.webContents,senderFrame:{}}, {messages:[{text:'subframe spoof'}]});
  ipcMain.emit('assistant:action', {sender:view.webContents,senderFrame:{}}, {action:'send',text:'subframe spoof'});
  assert.equal(sent.length, 0);
  ipcMain.emit('assistant:update', parent, { apiKey: 'not-forwarded',sourcePreview:{attached:true,summary:'Captions 0:00–1:30',detail:'Bounded excerpts',apiKey:'not-forwarded'},phase:'reasoning',palette:{accent:'#d5a35c',text:'url(secret)'}, locale: 'tr', scope: 'full',pinScope:'media',activeThread:'one',threads:[{id:'one',title:'First'}],messages: [{id:'reply', role: 'user', text: '<img onerror=bad>',links:[{id:'x'.repeat(85),excerpt:'verified'}],actions:[{id:'proposal',kind:'seek_to_time',canContinue:true,waiting:true,retryable:true,partial:true}]}] });
  assert.equal(sent[0].value.apiKey, undefined);assert.deepEqual(sent[0].value.sourcePreview,{attached:true,summary:'Captions 0:00–1:30',detail:'Bounded excerpts'});assert.equal(sent[0].value.phase,'reasoning');
  assert.equal(sent[0].value.messages[0].actions[0].canContinue,true);assert.equal(sent[0].value.messages[0].actions[0].waiting,true);assert.equal(sent[0].value.messages[0].actions[0].retryable,true);assert.equal(sent[0].value.messages[0].actions[0].partial,true);
  assert.deepEqual(sent[0].value.palette,{accent:'#d5a35c'});
  assert.equal(sent[0].value.activeThread,'one');assert.equal(sent[0].value.pinScope,'media');assert.equal(sent[0].value.messages[0].links[0].id.length,85);
  assert.equal(sent[0].value.messages[0].text, '<img onerror=bad>', 'Rendered as text by the view, never HTML');
  ipcMain.emit('assistant:update', parent, {messages:[{id:'podcast',role:'ai',text:'x',links:[{id:'b:1',label:'L',excerpt:'Quote',usage:'cited',state:'stale',note:'N'.repeat(900),action:'seek',meta:'M',scope:'S',title:'T',path:'C:\\private',url:'file:///private'},{id:'b:2',excerpt:'Q',usage:'danger',state:'exploit',action:'run'}]}]});
  const podcastLinks=sent.at(-1).value.messages[0].links;
  assert.deepEqual([podcastLinks[0].usage,podcastLinks[0].state,podcastLinks[0].action,podcastLinks[0].note.length],['cited','stale','seek',400]);
  assert.equal(podcastLinks[0].path,undefined);assert.equal(podcastLinks[0].url,undefined);
  assert.deepEqual([podcastLinks[1].usage,podcastLinks[1].state,podcastLinks[1].action],['','','']);
  const reference='P11111111-1111-1111-1111-111111111111';
  ipcMain.emit('assistant:update',parent,{messages:[{role:'ai',text:'Complete original',displayText:'Readable answer',links:[{id:'b:1',action:'text',canSearchAgain:true,reference},{id:'b:2',action:'run',canSearchAgain:true,reference:'file:///private'}]},{role:'user',text:'User text',displayText:'Do not hide user text'}]});
  const compact=sent.at(-1).value.messages;assert.equal(compact[0].displayText,'Readable answer');assert.equal(compact[0].text,'Complete original');assert.equal(compact[0].links[0].reference,reference);assert.equal(compact[0].links[0].canSearchAgain,true);assert.equal(compact[0].links[1].reference,'');assert.equal(compact[0].links[1].canSearchAgain,false);assert.equal(compact[1].displayText,undefined);
  ipcMain.emit('assistant:action',overlay,{action:'search-podcast-source',text:'b:1',sourceToken:'context'});assert.equal(sent.at(-1).value.action,'search-podcast-source');
  ipcMain.emit('assistant:update', parent, {sourceTarget:{kind:'podcast',id:'private-episode'},sourceToken:'podcast-thread'});
  assert.deepEqual(sent.at(-1).value.sourceTarget,{kind:'podcast'});
  ipcMain.emit('assistant:action', overlay, {action:'open-source',sourceToken:'podcast-thread'});
  assert.equal(sent.at(-1).value.action,'open-source');
  ipcMain.emit('assistant:update', parent, {sourceTarget:{kind:'unsupported'}});
  assert.equal(sent.at(-1).value.sourceTarget,null);
  ipcMain.emit('assistant:update', parent, {toolbarDocked:true});
  assert.equal(view.visible,false,'A toolbar entry replaces the collapsed floating bubble');
  ipcMain.emit('assistant:update', foreign, {toolbarDocked:false});
  assert.equal(view.visible,false,'Foreign contents cannot undo the docked presentation');
  ipcMain.emit('assistant:show', parent);
  assert.equal(view.visible,true,'The toolbar still opens the actual assistant');
  ipcMain.emit('assistant:action', overlay, {action:'toggle'});
  assert.equal(view.visible,false,'Closing the assistant restores the unobstructed toolbar mode');
  ipcMain.emit('assistant:update', parent, {toolbarDocked:false});
  assert.equal(view.visible,true,'Other screens retain the ordinary floating bubble');
  ipcMain.emit('assistant:update', parent, {busy:true,canRuntimeMessage:true,runtimeMessages:[{id:'queue-1',mode:'steer',status:'queued',apiKey:'private'}]});
  const runtime=sent.at(-1).value;assert.equal(runtime.canRuntimeMessage,true);assert.deepEqual(runtime.runtimeMessages,[{id:'queue-1',mode:'steer',status:'queued'}]);
  for(const action of ['steer','followup']){ipcMain.emit('assistant:action',overlay,{action,sourceToken:'same-source',requestId:'receipt-1',text:'next question'});assert.deepEqual(sent.at(-1).value,{action,sourceToken:'same-source',requestId:'receipt-1',text:'next question'});}
  ipcMain.emit('assistant:update',parent,{busy:false,canRuntimeMessage:true});assert.equal(sent.at(-1).value.canRuntimeMessage,false);
  ipcMain.emit('assistant:action', overlay, { action: 'toggle' });
  assert(view.bounds.width > 300 && view.bounds.width < 680);
  ipcMain.emit('assistant:action', overlay, { action: 'send', text: 'question' });
  assert.deepEqual(sent.at(-1), { channel: 'assistant:command', value: { action: 'send', sourceToken:'',requestId:'',text: 'question' } });
  ipcMain.emit('assistant:action',overlay,{action:'continue-tool',text:'proposal'});assert.equal(sent.at(-1).value.action,'continue-tool');
  ipcMain.emit('assistant:action',overlay,{action:'settings',text:'arbitrary section'});assert.equal(sent.at(-1).value.action,'settings');
  ipcMain.emit('assistant:show', foreign);
  ipcMain.emit('assistant:show', parent);
  assert.equal(sent.findLast(row=>row.channel==='assistant:snapshot').value.opened,true);
  assert(view.bounds.width>300);
  ipcMain.emit('assistant:modal-state',foreign,true);
  assert.equal(view.visible,true,'Foreign contents cannot hide the assistant');
  ipcMain.emit('assistant:modal-state',{sender:window.webContents,senderFrame:{}},true);
  assert.equal(view.visible,true,'Subframes cannot change modal ownership');
  ipcMain.emit('assistant:modal-state',parent,true);
  assert.equal(view.visible,false);
  const beforeBlocked=sent.length;
  ipcMain.emit('assistant:action',overlay,{action:'toggle'});
  ipcMain.emit('assistant:action',overlay,{action:'send',text:'behind modal'});
  ipcMain.emit('assistant:action',overlay,{action:'settings'});
  ipcMain.emit('assistant:show',parent);
  assert.equal(sent.length,beforeBlocked,'Hidden overlay cannot steal focus or send actions');
  window.emit('resize');
  view.webContents.emit('did-finish-load');
  assert.equal(view.visible,false,'Layout and overlay reload retain modal ownership');
  ipcMain.emit('assistant:modal-state',parent,false);
  assert.equal(view.visible,true);
  assert(view.bounds.width>300,'Existing expanded conversation survives modal close');
  ipcMain.emit('assistant:modal-state',parent,true);
  window.webContents.emit('dom-ready');
  assert.equal(view.visible,true,'Parent reload clears obsolete modal ownership');
  const parentContents=window.webContents;
  Object.defineProperty(window,'webContents',{get(){throw Error('BrowserWindow destroyed');}});
  window.emit('closed');
  assert.equal(ipcMain.listenerCount('assistant:modal-state'),0);
  assert.equal(parentContents.listenerCount('dom-ready'),0);
  assert.equal(ipcMain.listenerCount('assistant:show'),0);
  assert.equal(ipcMain.listenerCount('assistant:update'), 0);
  assert.equal(ipcMain.listenerCount('assistant:action'), 0);
});
