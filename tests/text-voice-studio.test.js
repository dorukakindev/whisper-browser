'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {EventEmitter}=require('node:events'),{PassThrough}=require('node:stream');
const wav=require('./helpers/wav-fixture');
const {settings,readText}=require('../src/text-voice-studio');

test('text studio validates settings and reads Turkish UTF-16 / Windows-1254',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'text-voice-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const file=path.join(root,'Türkçe.txt');
 fs.writeFileSync(file,Buffer.concat([Buffer.from([255,254]),Buffer.from('İyi günler, ışık.','utf16le')]));
 assert.equal(readText(file),'İyi günler, ışık.');
 fs.writeFileSync(file,Buffer.from([0x49,0xfe,0xfd,0x6b]));assert.equal(readText(file),'Işık');
 assert.equal(settings({steps:17,max_chars:400}).steps,17);
 assert.throws(()=>settings({batch:7}));assert.throws(()=>settings({normalize:'false'}));
});

test('text studio shares job ownership, preserves reference, cleans only failed output',async t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'text-voice-service-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const engine=path.join(root,'engine');fs.mkdirSync(path.join(engine,'.venv','Scripts'),{recursive:true});
 fs.writeFileSync(path.join(engine,'.venv','Scripts','python.exe'),'fixture');
 const reference=path.join(root,'reference.wav'),transcript=path.join(root,'reference.txt');
 fs.writeFileSync(reference,wav(480));fs.writeFileSync(transcript,'Original transcript.');
 const app=new EventEmitter();app.getPath=()=>root;
 const handlers={},events=[],children=[];let pick=reference;
 const sender=new EventEmitter();sender.isDestroyed=()=>false;sender.send=(_,event)=>events.push(event);
 const svc=require('../src/dub-service').registerDubService({app,ipcMain:{handle:(n,f)=>handlers[n]=f},
  dialog:{showOpenDialog:async()=>({canceled:false,filePaths:[pick]})},owner:()=>null,
  authorized:e=>e.sender===sender,authorizeSubtitle:async p=>p,busy:()=>false,grantMedia:()=>{},environment:()=>({}),
  spawn:(_python,args)=>{const p=new EventEmitter();p.stdout=new PassThrough();p.stderr=new PassThrough();
   p.request=JSON.parse(fs.readFileSync(args.at(-1),'utf8'));children.push(p);return p;},
  terminate:async p=>{p.emit('close',1,null);return true;}});
 fs.writeFileSync(path.join(root,'dub-settings.json'),JSON.stringify({engine,reference,transcript}));
 const call=request=>handlers['dub:textVoice']({sender},request);
 assert.equal((await handlers['dub:textVoice']({sender:{}},{action:'config'})).ok,false);
 const config=await call({action:'config'});assert(config.referenceReady);assert(config.referenceId.startsWith('local:'));
 const originalSettings=fs.readFileSync(path.join(root,'dub-settings.json'),'utf8');
 const imported=await call({action:'save-reference',referenceId:config.referenceId,name:'Paylaşılan Türkçe ses',transcript:'Saved edited transcript.'});
 assert(imported.ok);assert.equal(imported.reference.name,'Paylaşılan Türkçe ses');
 assert.equal(imported.reference.transcriptBaseline,null,'manual text is not automatic ASR evidence');
 assert.deepEqual(fs.readFileSync(imported.reference.path),fs.readFileSync(reference));
 assert.equal(fs.readFileSync(transcript,'utf8'),'Original transcript.');
 assert.equal(fs.readFileSync(path.join(root,'dub-settings.json'),'utf8'),originalSettings,'save does not set global default');
 assert((await handlers['dub:references']({sender})).references.some(v=>v.id===imported.reference.id));
 assert.equal((await call({action:'save-reference',referenceId:'local:forged',name:'No',transcript:'No'})).ok,false);
 assert.equal((await call({action:'save-reference',referenceId:config.referenceId,name:'',transcript:'No'})).ok,false);
 assert((await handlers['dub:referenceUse']({sender},{id:imported.reference.id})).ok);
 assert.equal((await call({action:'config'})).libraryId,imported.reference.id);
 const start={action:'start',referenceId:config.referenceId,text:'A complete sentence.',transcript:'Edited draft.',settings:{},name:'Türkçe / output'};
 assert.equal((await call({...start,referenceId:'local:invented'})).ok,false);
 const result=await call(start);assert(result.ok);assert(svc.running());assert.equal(children.length,1);
 assert.equal((await call(start)).ok,false,'duplicate blocked');
 assert.equal((await call({action:'save-reference',referenceId:config.referenceId,name:'Busy',transcript:'No'})).ok,false);
 assert.equal((await call({action:'pick-reference'})).ok,false,'reference cannot change during production');
 const output=children[0].request.output;fs.writeFileSync(output,wav(480));
 children[0].stdout.write('[1/1] complete\n');children[0].emit('close',0,null);
 assert.equal(svc.running(),false);assert(events.some(e=>e.type==='done'&&e.kind==='text'));
 const recent=await call({action:'history'});assert.equal(recent.results.length,1);
 assert.equal(recent.results[0].id,result.id);
 const reopened=await call({action:'open-result',id:result.id});assert(reopened.ok);assert.equal(reopened.result.path,output);
 assert.equal((await call({action:'open-result',id:'../../outside'})).ok,false);
 const restarted=require('../src/text-voice-history').createTextVoiceHistory(app);
 assert.equal(restarted.list()[0].id,result.id,'new service restores the completed record');
 fs.rmSync(path.join(root,'text-voice-history.json'));
 assert.equal(restarted.list()[0].id,result.id,'existing production logs adopted without an index');
 assert.equal(fs.readFileSync(transcript,'utf8'),'Original transcript.');
 assert.equal(fs.readFileSync(children[0].request.transcript,'utf8'),'Edited draft.');
 assert((await call(start)).ok);const cancelled=children[1].request.output;
 fs.writeFileSync(cancelled,wav(480));fs.writeFileSync(cancelled.replace(/\.wav$/,'.tmp.wav'),wav());
 assert((await svc.cancel()).ok);assert.equal(svc.running(),false);
 assert(!fs.existsSync(cancelled));assert(!fs.existsSync(cancelled.replace(/\.wav$/,'.tmp.wav')));
 assert(fs.existsSync(output),'previous completed output retained');
 assert(events.some(e=>e.type==='cancelled'&&e.kind==='text'));
 assert.equal((await call({action:'history'})).results.length,1,'cancelled production is not ready history');
 const originalOutput=fs.readFileSync(output);fs.writeFileSync(output,'broken WAV');
 assert.equal((await call({action:'history'})).results.length,0);
 assert.equal((await call({action:'open-result',id:result.id})).ok,false,'corrupt WAV cannot reopen as ready');
 fs.writeFileSync(output,originalOutput);
 const historyRequest=path.join(root,'Sesler','Girdi','Metin',result.id,'request.json');
 const originalRequest=fs.readFileSync(historyRequest,'utf8'),outside=path.join(root,'outside-'+result.id+'.wav');fs.writeFileSync(outside,wav());
 fs.writeFileSync(historyRequest,JSON.stringify({...JSON.parse(originalRequest),output:outside}));
 assert.equal((await call({action:'open-result',id:result.id})).ok,false,'record cannot grant arbitrary outside audio');
 fs.writeFileSync(historyRequest,originalRequest);
 const ownedId='text-11111111-2222-4333-8444-555555555555';
 assert.equal((await call({...start,id:'../../outside'})).ok,false,'client correlation identity is constrained');
 const owned=await call({...start,id:ownedId});assert(owned.ok);assert.equal(owned.id,ownedId);
 assert.equal(children.length,3);
 const staleStop=await handlers['dub:cancel']({sender},{id:result.id});assert(staleStop.ok&&staleStop.stale);assert(svc.running(),'old scoped cancellation cannot terminate the newer text job');
 assert.equal((await handlers['dub:cancel']({sender},{id:''})).ok,false);assert(svc.running());
 assert((await handlers['dub:cancel']({sender},{id:ownedId})).ok);assert.equal(svc.running(),false);
 assert(events.some(e=>e.id===ownedId&&e.kind==='text'&&e.type==='cancelled'));
 assert.equal((await call({...start,id:ownedId})).ok,false,'completed input scope cannot be reused to overwrite its request');
 await handlers['dub:textUI']({sender});assert.equal(events.at(-1).type,'text_studio_open');
 assert.equal(children.length,3,'opening Electron studio must not spawn Tk');
});
